"""Integrity and limiting-case checks for post-main extensions."""
import json,math
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parent;checks=[]
def add(name,passed,measured=None):checks.append({'name':name,'pass':bool(passed),'measured':measured})
def read(name):return json.load(open(ROOT/name))
r=read('refinement.json');err=max(x['step_halving_N_difference'] for x in r);add('refined_abundance_step_halving',err<1e-6,err)
s=read('selection_refinement.json');add('selection_roots_bracketed',all(x['sign_change'][0]>0>x['sign_change'][1] for a in s for x in a['roots']))
add('expanded_selection_domain_labeled',all(x['main_domain']==(.5<=x['tau']<=12) for a in s for x in a['roots']))
f=read('frozen_replacement.json');freq=np.asarray(f['frequency']);N=np.asarray(f['N']);add('replacement_frequency_accounting',np.max(abs(freq.sum(axis=0)-1))<1e-12 and np.min(freq)>=0 and np.max(freq)<=1)
add('replacement_positive_density',np.min(N)>0,float(np.min(N)))
add('rare_initial_frequency',abs(freq[1,0]-.001)<1e-12,float(freq[1,0]))
add('replacement_endpoint_export',abs(freq[1,-1]-f['final_frozen_fraction'])<1e-14 and abs(N[-1]-f['final_N'])<1e-10)
conv=read('dynamic_convergence.json');add('dynamic_step_halving_full_precision',conv['max_absolute_difference']<1e-7,conv['max_absolute_difference'])
add('dynamic_self_relative_full_precision',abs(conv['self_relative'])<1e-10,conv['self_relative'])
# Every invariant in the cohort companions is generated by their own shared-seed checks.
for name in ['repertoire.json','repertoire_tutors.json']:
 obj=read(name);inv=obj['invariants'];add(name+'_invariants_pass',bool(inv) and all(x.get('passed',False) for x in inv.values()))
add('bayesian_benchmark_valid',all(c['passed'] for c in read('bayes_benchmark.json')['checks']))
out={'pass':all(c['pass'] for c in checks),'checks':checks};(ROOT/'followup_verification.json').write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out,indent=2))
if not out['pass']:raise SystemExit(1)
